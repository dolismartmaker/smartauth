/**
 * Tests for the dmTicket mapper.
 *
 * They cover the three defects fixed on that mapper, each one falsifiable:
 * neutralise the fix and the matching test goes red.
 *
 *   1. note_public / note_private / email_from were published (and the two
 *      notes were writable) although llx_ticket has no such column and
 *      Ticket::update() never writes them -- a write answered 200 and lost the
 *      value. testGhostColumnsDoNotExistInLlxTicket proves the premise against
 *      the real schema, so the removal cannot be a guess.
 *   2. the published `status` key addresses the PHP property Ticket::fetch()
 *      aliases from fk_statut, which the catalog derivation cannot see, so the
 *      status filter and sort were silently dropped. The two SQL tests below
 *      assert the produced fragments really name fk_statut.
 *   3. creation through the generic facade is impossible (ref required, not
 *      generated by create(), not writable, no pre-create hook).
 *
